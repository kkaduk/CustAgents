-- =============================================================================
-- ORACLE EXADATA DDL & SCHEMA SEPARATION FOR BANKING SITUATION AWARENESS
-- Implements Section 2, 3, 4, 5, 9, and 11 of Doc/ExaPekdoDesign.md
-- =============================================================================
-- Six Logical Schemas in Oracle Exadata:
--   1. SA_PERSISTENCE  : Pekko Event Journal (OracleProfile), Snapshots, Durable State, Transactional Outbox
--   2. SA_FACTS        : Authoritative canonical transactions, verified documents, debt obligations
--   3. SA_GRAPH        : Oracle Property Graph (vertices, edges, global relationship graph)
--   4. SA_INTELLIGENCE : Global risk signals (NetworkRiskPatternDetected) & portfolio analytics
--   5. SA_DECISIONS    : Immutable decision evaluations, situation projections, regulatory audit evidence
--   6. SA_GOVERNANCE   : Rule versions, scoring models, policies, and data completeness governance
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. SCHEMA: SA_PERSISTENCE (Pekko Persistence JDBC - Slick OracleProfile)
-- -----------------------------------------------------------------------------
CREATE USER SA_PERSISTENCE IDENTIFIED BY "Exadata_SA_Persist_2026#";
GRANT CONNECT, RESOURCE, UNLIMITED TABLESPACE TO SA_PERSISTENCE;

CREATE TABLE SA_PERSISTENCE.EVENT_JOURNAL (
    ORDERING             NUMBER(19) GENERATED ALWAYS AS IDENTITY NOT NULL,
    PERSISTENCE_ID       VARCHAR2(255 CHAR) NOT NULL,
    SEQUENCE_NUMBER      NUMBER(19) NOT NULL,
    DELETED              NUMBER(1) DEFAULT 0 NOT NULL,
    WRITER               VARCHAR2(255 CHAR) NOT NULL,
    WRITE_TIMESTAMP      NUMBER(19) NOT NULL,
    ADAPTER_MANIFEST     VARCHAR2(255 CHAR) NOT NULL,
    EVENT_SER_ID         NUMBER(10) NOT NULL,
    EVENT_SER_MANIFEST   VARCHAR2(255 CHAR) NOT NULL,
    EVENT_PAYLOAD        BLOB NOT NULL,
    META_SER_ID          NUMBER(10),
    META_SER_MANIFEST    VARCHAR2(255 CHAR),
    META_PAYLOAD         BLOB,
    EVENT_SCHEMA_VERSION NUMBER(10) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_EVENT_JOURNAL PRIMARY KEY (PERSISTENCE_ID, SEQUENCE_NUMBER)
);

CREATE UNIQUE INDEX SA_PERSISTENCE.IDX_EVENT_JOURNAL_ORDERING
    ON SA_PERSISTENCE.EVENT_JOURNAL (ORDERING);

CREATE TABLE SA_PERSISTENCE.EVENT_TAG (
    EVENT_ID NUMBER(19) NOT NULL,
    TAG      VARCHAR2(255 CHAR) NOT NULL,
    CONSTRAINT PK_EVENT_TAG PRIMARY KEY (EVENT_ID, TAG),
    CONSTRAINT FK_EVENT_TAG_JOURNAL FOREIGN KEY (EVENT_ID)
        REFERENCES SA_PERSISTENCE.EVENT_JOURNAL (ORDERING) ON DELETE CASCADE
);

CREATE TABLE SA_PERSISTENCE.SNAPSHOT (
    PERSISTENCE_ID        VARCHAR2(255 CHAR) NOT NULL,
    SEQUENCE_NUMBER       NUMBER(19) NOT NULL,
    CREATED               NUMBER(19) NOT NULL,
    SNAPSHOT_SER_ID       NUMBER(10) NOT NULL,
    SNAPSHOT_SER_MANIFEST VARCHAR2(255 CHAR) NOT NULL,
    SNAPSHOT_PAYLOAD      BLOB NOT NULL,
    META_SER_ID           NUMBER(10),
    META_SER_MANIFEST     VARCHAR2(255 CHAR),
    META_PAYLOAD          BLOB,
    STATE_VERSION         NUMBER(19) DEFAULT 1 NOT NULL,
    RULE_VERSION          VARCHAR2(64 CHAR) NOT NULL,
    CONSTRAINT PK_SNAPSHOT PRIMARY KEY (PERSISTENCE_ID, SEQUENCE_NUMBER)
);

CREATE TABLE SA_PERSISTENCE.DURABLE_STATE (
    GLOBAL_OFFSET        NUMBER(19) GENERATED ALWAYS AS IDENTITY NOT NULL,
    PERSISTENCE_ID       VARCHAR2(255 CHAR) NOT NULL,
    REVISION             NUMBER(19) NOT NULL,
    STATE_PAYLOAD        BLOB NOT NULL,
    STATE_SER_ID         NUMBER(10) NOT NULL,
    STATE_SER_MANIFEST   VARCHAR2(255 CHAR),
    TAG                  VARCHAR2(255 CHAR),
    STATE_TIMESTAMP      NUMBER(19) NOT NULL,
    CONSTRAINT PK_DURABLE_STATE PRIMARY KEY (PERSISTENCE_ID)
);

-- Transactional Outbox for Reliable Inter-Agent & Kafka Signal Delivery (Section 10)
CREATE TABLE SA_PERSISTENCE.AGENT_TRANSACTIONAL_OUTBOX (
    OUTBOX_ID          VARCHAR2(128 CHAR) NOT NULL,
    PERSISTENCE_ID     VARCHAR2(255 CHAR) NOT NULL,
    SEQUENCE_NUMBER    NUMBER(19) NOT NULL,
    TARGET_AGENT_TYPE  VARCHAR2(64 CHAR) NOT NULL,
    TARGET_ENTITY_ID   VARCHAR2(128 CHAR) NOT NULL,
    MESSAGE_TYPE       VARCHAR2(128 CHAR) NOT NULL,
    PAYLOAD_JSON       CLOB NOT NULL,
    DELIVERY_STATUS    VARCHAR2(32 CHAR) DEFAULT 'PENDING' NOT NULL,
    ATTEMPT_COUNT      NUMBER(10) DEFAULT 0 NOT NULL,
    CREATED_AT         TIMESTAMP WITH TIME ZONE NOT NULL,
    DELIVERED_AT       TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_AGENT_OUTBOX PRIMARY KEY (OUTBOX_ID)
);

-- -----------------------------------------------------------------------------
-- 2. SCHEMA: SA_FACTS (Authoritative Financial & Document Facts - Section 4)
-- -----------------------------------------------------------------------------
CREATE USER SA_FACTS IDENTIFIED BY "Exadata_SA_Facts_2026#";
GRANT CONNECT, RESOURCE, UNLIMITED TABLESPACE TO SA_FACTS;

CREATE TABLE SA_FACTS.FINANCIAL_TRANSACTION_FACTS (
    TX_ID                       VARCHAR2(128 CHAR) NOT NULL,
    CUSTOMER_ID                 VARCHAR2(128 CHAR) NOT NULL,
    COUNTERPARTY_ID             VARCHAR2(128 CHAR) NOT NULL,
    COUNTERPARTY_IS_BANK_CLIENT NUMBER(1) NOT NULL,
    DIRECTION                   VARCHAR2(16 CHAR) NOT NULL,
    AMOUNT                      NUMBER(19, 4) NOT NULL,
    CURRENCY                    VARCHAR2(8 CHAR) NOT NULL,
    CATEGORY                    VARCHAR2(64 CHAR) NOT NULL,
    CATEGORIZER_SOURCE          VARCHAR2(64 CHAR) NOT NULL,
    RESULTS_IN_OVERDRAFT        NUMBER(1) NOT NULL,
    RESTRICTED_ENTITY_ID        VARCHAR2(128 CHAR),
    RESTRICTED_LEVEL            VARCHAR2(64 CHAR),
    OCCURRED_AT                 TIMESTAMP WITH TIME ZONE NOT NULL,
    PROJECTED_AT                TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_FIN_TX_FACTS PRIMARY KEY (TX_ID, CUSTOMER_ID, DIRECTION)
);

CREATE INDEX SA_FACTS.IDX_FIN_TX_CUSTOMER_TIME
    ON SA_FACTS.FINANCIAL_TRANSACTION_FACTS (CUSTOMER_ID, OCCURRED_AT DESC);

CREATE TABLE SA_FACTS.VERIFIED_DOCUMENT_FACTS (
    DOC_ID        VARCHAR2(128 CHAR) NOT NULL,
    CUSTOMER_ID   VARCHAR2(128 CHAR) NOT NULL,
    FACT_TYPE     VARCHAR2(64 CHAR) NOT NULL,
    NUMERIC_VALUE NUMBER(19, 4),
    TEXT_VALUE    VARCHAR2(512 CHAR),
    ISSUER        VARCHAR2(255 CHAR) NOT NULL,
    VERIFIED_BY   VARCHAR2(128 CHAR) NOT NULL,
    VERIFIED_AT   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_VERIFIED_DOC_FACTS PRIMARY KEY (DOC_ID)
);

CREATE TABLE SA_FACTS.DEBT_OBLIGATION_FACTS (
    OBLIGATION_ID       VARCHAR2(128 CHAR) NOT NULL,
    CUSTOMER_ID         VARCHAR2(128 CHAR) NOT NULL,
    CREDITOR_NAME       VARCHAR2(255 CHAR) NOT NULL,
    MONTHLY_INSTALLMENT NUMBER(19, 4) NOT NULL,
    OUTSTANDING_BALANCE NUMBER(19, 4) NOT NULL,
    SOURCE_DOC_ID       VARCHAR2(128 CHAR) NOT NULL,
    UPDATED_AT          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_DEBT_OBLIGATION_FACTS PRIMARY KEY (OBLIGATION_ID)
);

-- -----------------------------------------------------------------------------
-- 3. SCHEMA: SA_GRAPH (Oracle Property Graph for Global Relationship Analysis - Section 5)
-- -----------------------------------------------------------------------------
CREATE USER SA_GRAPH IDENTIFIED BY "Exadata_SA_Graph_2026#";
GRANT CONNECT, RESOURCE, UNLIMITED TABLESPACE TO SA_GRAPH;

CREATE TABLE SA_GRAPH.GRAPH_VERTICES (
    VERTEX_ID       VARCHAR2(128 CHAR) NOT NULL,
    VERTEX_TYPE     VARCHAR2(64 CHAR) NOT NULL, -- 'BANK_CUSTOMER', 'EXTERNAL_ENTITY', 'COMPANY', 'RESTRICTED_ENTITY'
    SEGMENT_ID      VARCHAR2(64 CHAR),
    INTRINSIC_RISK  NUMBER(5, 4) DEFAULT 0.0 NOT NULL,
    DEGREE_CENTRALITY NUMBER(10) DEFAULT 0 NOT NULL,
    COMMUNITY_ID    VARCHAR2(128 CHAR),
    LAST_UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_GRAPH_VERTICES PRIMARY KEY (VERTEX_ID)
);

CREATE TABLE SA_GRAPH.GRAPH_EDGES (
    EDGE_ID          VARCHAR2(255 CHAR) NOT NULL,
    SOURCE_VERTEX_ID VARCHAR2(128 CHAR) NOT NULL,
    TARGET_VERTEX_ID VARCHAR2(128 CHAR) NOT NULL,
    RELATIONSHIP_TYPE VARCHAR2(64 CHAR) NOT NULL, -- 'TRANSFERS_TO', 'SHARED_COUNTERPARTY', 'CORPORATE_LINK'
    TOTAL_VOLUME     NUMBER(19, 4) NOT NULL,
    TX_COUNT         NUMBER(10) NOT NULL,
    EVIDENCE_TX_IDS  VARCHAR2(2000 CHAR),
    LAST_ACTIVE_AT   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_GRAPH_EDGES PRIMARY KEY (EDGE_ID),
    CONSTRAINT FK_EDGE_SRC FOREIGN KEY (SOURCE_VERTEX_ID) REFERENCES SA_GRAPH.GRAPH_VERTICES (VERTEX_ID),
    CONSTRAINT FK_EDGE_TGT FOREIGN KEY (TARGET_VERTEX_ID) REFERENCES SA_GRAPH.GRAPH_VERTICES (VERTEX_ID)
);

-- Oracle 23ai / Exadata SQL Property Graph definition:
-- CREATE PROPERTY GRAPH SA_GRAPH.SA_GLOBAL_RELATIONSHIP_GRAPH
--   VERTEX TABLES (SA_GRAPH.GRAPH_VERTICES KEY (VERTEX_ID) PROPERTIES ARE ALL COLUMNS)
--   EDGE TABLES (SA_GRAPH.GRAPH_EDGES KEY (EDGE_ID)
--     SOURCE KEY (SOURCE_VERTEX_ID) REFERENCES GRAPH_VERTICES (VERTEX_ID)
--     DESTINATION KEY (TARGET_VERTEX_ID) REFERENCES GRAPH_VERTICES (VERTEX_ID)
--     PROPERTIES ARE ALL COLUMNS);

-- -----------------------------------------------------------------------------
-- 4. SCHEMA: SA_INTELLIGENCE (Global Risk Signals & Portfolio Analytics - Section 5, 11, 14)
-- -----------------------------------------------------------------------------
CREATE USER SA_INTELLIGENCE IDENTIFIED BY "Exadata_SA_Intel_2026#";
GRANT CONNECT, RESOURCE, UNLIMITED TABLESPACE TO SA_INTELLIGENCE;

CREATE TABLE SA_INTELLIGENCE.RISK_INTELLIGENCE_EVENTS (
    PATTERN_ID           VARCHAR2(128 CHAR) NOT NULL,
    PATTERN_TYPE         VARCHAR2(64 CHAR) NOT NULL, -- 'SHARED_HIGH_RISK_COUNTERPARTY', 'HIGH_DEGREE_HUB', 'COMMUNITY_RING', 'SEGMENT_CONCENTRATION'
    AFFECTED_CUSTOMER_ID VARCHAR2(128 CHAR) NOT NULL,
    SHARED_ENTITY_ID     VARCHAR2(128 CHAR) NOT NULL,
    LINKED_CUSTOMERS     VARCHAR2(2000 CHAR) NOT NULL,
    RISK_SCORE           NUMBER(5, 4) NOT NULL,
    REASON_CODE          VARCHAR2(64 CHAR) NOT NULL,
    DESCRIPTION          VARCHAR2(1000 CHAR) NOT NULL,
    EVIDENCE_IDS         VARCHAR2(2000 CHAR) NOT NULL,
    DETECTED_AT          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_RISK_INTEL_EVENTS PRIMARY KEY (PATTERN_ID, AFFECTED_CUSTOMER_ID)
);

CREATE TABLE SA_INTELLIGENCE.PORTFOLIO_ANALYTICS_SNAPSHOTS (
    SNAPSHOT_ID            VARCHAR2(128 CHAR) NOT NULL,
    SEGMENT_ID             VARCHAR2(64 CHAR) NOT NULL,
    ACTIVE_CUSTOMERS_COUNT NUMBER(10) NOT NULL,
    AVG_MONTHLY_INCOME     NUMBER(19, 4) NOT NULL,
    HIGH_RISK_CUSTOMERS    NUMBER(10) NOT NULL,
    CONCENTRATION_INDEX    NUMBER(5, 4) NOT NULL,
    COMPUTED_AT            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_PORTFOLIO_SNAPSHOTS PRIMARY KEY (SNAPSHOT_ID)
);

-- -----------------------------------------------------------------------------
-- 5. SCHEMA: SA_DECISIONS (Persisted Evaluations, Projections & Audit - Section 7, 11, 13)
-- -----------------------------------------------------------------------------
CREATE USER SA_DECISIONS IDENTIFIED BY "Exadata_SA_Decisions_2026#";
GRANT CONNECT, RESOURCE, UNLIMITED TABLESPACE TO SA_DECISIONS;

CREATE TABLE SA_DECISIONS.SITUATION_PROJECTION_LOG (
    PROJECTION_ID       VARCHAR2(128 CHAR) NOT NULL,
    APPLICATION_ID      VARCHAR2(128 CHAR) NOT NULL,
    CUSTOMER_ID         VARCHAR2(128 CHAR) NOT NULL,
    STATE_VERSION       NUMBER(19) NOT NULL,
    RULE_VERSION        VARCHAR2(64 CHAR) NOT NULL,
    DATA_COMPLETENESS   NUMBER(5, 4) NOT NULL,
    FUTURE_DTI          NUMBER(7, 4) NOT NULL,
    EXPECTED_LIQUIDITY  NUMBER(19, 4) NOT NULL,
    RISK_EXPOSURE_SCORE NUMBER(5, 4) NOT NULL,
    IS_AFFORDABLE       NUMBER(1) NOT NULL,
    PROJECTED_AT        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_SITUATION_PROJECTION_LOG PRIMARY KEY (PROJECTION_ID)
);

CREATE TABLE SA_DECISIONS.DECISION_AUDIT_LOG (
    APPLICATION_ID       VARCHAR2(128 CHAR) NOT NULL,
    CUSTOMER_ID          VARCHAR2(128 CHAR) NOT NULL,
    OUTCOME_STATUS       VARCHAR2(32 CHAR) NOT NULL,
    CREDIT_SCORE         NUMBER(10) NOT NULL,
    STATE_VERSION        NUMBER(19) NOT NULL,
    POLICY_VERSION       VARCHAR2(64 CHAR) NOT NULL,
    DATA_COMPLETENESS    NUMBER(5, 4) NOT NULL,
    REASON_CODES         VARCHAR2(1000 CHAR),
    STATEMENT_OF_REASONS CLOB NOT NULL,
    EVALUATED_AT         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_DECISION_AUDIT_LOG PRIMARY KEY (APPLICATION_ID)
);

-- -----------------------------------------------------------------------------
-- 6. SCHEMA: SA_GOVERNANCE (Rule Versions, Models, Policies & Control Metadata - Section 11, 13)
-- -----------------------------------------------------------------------------
CREATE USER SA_GOVERNANCE IDENTIFIED BY "Exadata_SA_Gov_2026#";
GRANT CONNECT, RESOURCE, UNLIMITED TABLESPACE TO SA_GOVERNANCE;

CREATE TABLE SA_GOVERNANCE.GOVERNANCE_POLICY_REGISTRY (
    POLICY_VERSION           VARCHAR2(64 CHAR) NOT NULL,
    MODEL_NAME               VARCHAR2(128 CHAR) NOT NULL,
    MAX_DTI_RATIO            NUMBER(5, 4) NOT NULL,
    MAX_HIGH_RISK_SPEND      NUMBER(5, 4) NOT NULL,
    MAX_OVERDRAFT_COUNT      NUMBER(10) NOT NULL,
    MAX_1HOP_RISK_SCORE      NUMBER(5, 4) NOT NULL,
    MAX_2HOP_RISK_SCORE      NUMBER(5, 4) NOT NULL,
    MIN_COMPLETENESS_SCORE   NUMBER(5, 4) NOT NULL,
    ACTIVE_FLAG              NUMBER(1) DEFAULT 1 NOT NULL,
    REGISTERED_AT            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_GOV_POLICY_REGISTRY PRIMARY KEY (POLICY_VERSION)
